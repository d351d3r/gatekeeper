package io.gatekeeper.util

/**
 * Нужно ли предупреждать перед установкой пакета.
 *
 * На MIUI/HyperOS сессия установки внутри рабочего профиля зависает на экране
 * системного установщика, а кнопка «всё равно продолжить» ведёт в тот же
 * тупик (4PDA #2105, #2113; в апстриме гард MIUI есть только на пути клонирования,
 * путь установки APK гарда не проходил). Предупреждаем до запуска сессии и даём
 * отмену с честным отказом вызывающей стороне, вместо молчаливого висяка.
 *
 * В основном профиле предупреждение не показываем: зависание подтверждено
 * только для установки в контексте рабочего профиля.
 *
 * Вынесено в чистый класс без зависимости от Android SDK, чтобы решение
 * покрывалось JVM-тестами (см. InstallWarnPolicyTest).
 */
object InstallWarnPolicy {
    fun shouldWarn(isMiui: Boolean, isProfileOwner: Boolean): Boolean = isMiui && !isProfileOwner
}
