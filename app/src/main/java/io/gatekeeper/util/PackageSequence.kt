package io.gatekeeper.util

/**
 * Водяной знак состава пакетов профиля поверх `PackageManager.getChangedPackages`.
 *
 * Номер последовательности растет на каждое изменение состава у пользователя.
 * Спросить «менялось ли что-то с номера N» стоит одной транзакции, тогда как
 * перечисление списка обходится в несколько IPC на каждый пакет.
 */
object PackageSequence {

    /** Водяного знака нет: `getChangedPackages` появился в Android 8. */
    const val UNSUPPORTED = -1

    /** Номер, с которого спрашивают в первый раз: до него изменений не помним. */
    const val FROM_SCRATCH = 0

    /**
     * Первый ответ -- только базовая отметка: сравнивать не с чем, и обновлять
     * список не по чему. Иначе каждый вход в приложение давал бы ложное обновление.
     */
    fun changed(previous: Int?, current: Int): Boolean =
        previous != null && previous != current
}
